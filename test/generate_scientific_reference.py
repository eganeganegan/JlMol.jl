"""Regenerate the independent crambin reference values and small TRR fixtures."""

import argparse
import itertools
import json
import struct
from pathlib import Path

import Bio
from Bio.PDB.vectors import Vector, calc_angle, calc_dihedral
import numpy as np
import scipy
from scipy.spatial.distance import cdist, euclidean
from scipy.spatial.transform import Rotation


ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "test" / "data"


def trr_frame(points, cell, time, step, *, positions=True):
    """Write one single-precision GROMACS XDR record, using nm and ps."""
    version = b"GMX_trn_file"
    box = (np.diag(cell) / 10).astype(">f4").tobytes()
    coordinates = (points / 10).astype(">f4").tobytes()
    x_size, v_size = (len(coordinates), 0) if positions else (0, len(coordinates))
    sizes = (0, 0, len(box), 0, 0, 0, 0, x_size, v_size, 0)
    return (
        struct.pack(">3i", 1993, len(version) + 1, len(version))
        + version
        + struct.pack(">13i2f", *sizes, len(points), step, 0, time, 0.0)
        + box
        + (coordinates if positions else bytes(v_size))
    )


def fit(mobile, reference):
    mobile_center = mobile.mean(axis=0)
    reference_center = reference.mean(axis=0)
    rotation, _ = Rotation.align_vectors(reference - reference_center, mobile - mobile_center)
    translation = reference_center - rotation.apply(mobile_center)
    return rotation.as_matrix(), translation, rotation.apply(mobile) + translation


def rmsd(first, second):
    return np.sqrt(np.mean(np.sum((first - second) ** 2, axis=-1), axis=-1))


def rmsf(frames):
    return np.sqrt(np.var(frames, axis=0, ddof=0).sum(axis=-1))


def values_toml(sections):
    lines = ["# Generated by test/generate_scientific_reference.py."]
    for section, values in sections.items():
        lines.extend(("", f"[{section}]"))
        for key, value in values.items():
            if isinstance(value, (np.ndarray, np.floating)):
                value = value.round(10).tolist()
            elif isinstance(value, float):
                value = round(value, 10)
            if key == "contact_pairs":
                lines.append("contact_pairs = [")
                lines.extend(f"    {json.dumps(pair)}," for pair in value)
                lines.append("]")
            else:
                lines.append(f"{key} = {json.dumps(value)}")
    return ("\n".join(lines) + "\n").encode()


def generate():
    records = [line for line in (ROOT / "resources/1CRN.pdb").read_text().splitlines() if line.startswith("ATOM  ")]
    ids = [int(record[6:11]) for record in records]
    assert ids == list(range(1, 328))
    points = np.array([[float(record[start : start + 8]) for start in (30, 38, 46)] for record in records])
    alpha = np.array([i for i, record in enumerate(records) if record[12:16].strip() == "CA"])

    distance_ids = [2, 73]
    angle_ids = [[1, 2, 3], [3, 8, 9]]
    torsion_ids = [[1, 2, 3, 8], [3, 8, 9, 10]]

    def vectors(atom_ids):
        return [Vector(points[index - 1]) for index in atom_ids]

    cutoff = 8.0
    pairwise = cdist(points[alpha], points[alpha])
    pairs = np.argwhere(np.triu(pairwise <= cutoff, k=1))

    frames = [points]
    index = np.arange(len(points))
    drift = np.column_stack((index % 7 - 3, index % 5 - 2, index % 11 - 5))
    for step in range(1, 5):
        rotation = Rotation.from_euler("xyz", [9 * step, -7 * step, 16 * step], degrees=True)
        frames.append(rotation.apply(points + drift * (0.012 * step)) + [2.5 * step, -step, 0.75 * step])
    frames = np.asarray(frames)
    cells = np.array([[40, 48, 56], [42, 50, 59], [46, 51, 62], [38, 47, 55], [43, 52, 60]])
    times = [2.5, 5.0, 8.5, 13.0, 21.5]
    periodic_ids = [2, 9]
    frames[3, periodic_ids[1] - 1] += cells[3] * [1, -1, 0]
    delta = frames[3, periodic_ids[1] - 1] - frames[3, periodic_ids[0] - 1]
    lattice = np.array(list(itertools.product(range(-2, 3), repeat=3))) * cells[3]

    # Sparse samples make wrong atom order or a mismatched frame visible without duplicating every coordinate.
    sample_ids = [327, 2, 9, 73, 141]
    sample = np.array(sample_ids) - 1
    subset_ids = (alpha[[31, 0, 14, 45, 9, 1]] + 1).tolist()
    subset_frames = frames[:, np.array(subset_ids) - 1]
    reference = frames[1]
    all_fits = np.array([fit(frame, reference)[2] for frame in frames])
    subset_fits = np.array([fit(frame, subset_frames[1])[2] for frame in subset_frames[::2]])
    rotation, translation, aligned = fit(frames[2], reference)

    values = values_toml({
        "provenance": {"numpy": np.__version__, "scipy": scipy.__version__, "biopython": Bio.__version__},
        "structure": {
            "distance_ids": distance_ids,
            "distance": euclidean(*(points[np.array(distance_ids) - 1])),
            "angle_ids": angle_ids,
            "angles": np.degrees([calc_angle(*vectors(atom_ids)) for atom_ids in angle_ids]),
            "dihedral_ids": torsion_ids,
            "dihedrals": np.degrees([calc_dihedral(*vectors(atom_ids)) for atom_ids in torsion_ids]),
            "contact_cutoff": cutoff,
            "contact_ids": alpha + 1,
            "contact_pairs": alpha[pairs] + 1,
        },
        "trajectory": {
            "times_ps": times,
            "box_lengths": cells,
            "sample_ids": sample_ids,
            "sample_positions": frames[:, sample],
            "periodic_ids": periodic_ids,
            "periodic_distance": np.linalg.norm(delta + lattice, axis=1).min(),
            "nonperiodic_distance": np.linalg.norm(delta),
            "rmsd_raw": rmsd(frames, reference),
            "rmsd_aligned": rmsd(all_fits, reference),
            "rmsf_raw": rmsf(frames)[sample],
            "rmsf_aligned": rmsf(all_fits)[sample],
            "subset_ids": subset_ids,
            "subset_rmsd_raw": rmsd(subset_frames[::2], subset_frames[1]),
            "subset_rmsd_aligned": rmsd(subset_fits, subset_frames[1]),
            "subset_rmsf_raw": rmsf(subset_frames[::2]),
            "subset_rmsf_aligned": rmsf(subset_fits),
        },
        "fit_3_to_2": {"rotation": rotation, "translation": translation, "positions": aligned[sample]},
    })
    records = [trr_frame(frame, cell, time, i * 100) for i, (frame, cell, time) in enumerate(zip(frames, cells, times))]
    velocity_only = trr_frame(frames[1], cells[1], times[1], 100, positions=False)
    return {
        "crambin_reference.toml": values,
        "crambin_reference.trr": b"".join(records),
        "crambin_missing_positions.trr": records[0] + velocity_only,
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check fixture bytes without rewriting them.")
    options = parser.parse_args()
    for name, contents in generate().items():
        path = DATA / name
        if options.check:
            if path.read_bytes() != contents:
                raise SystemExit(f"Fixture differs: {path}")
        else:
            path.write_bytes(contents)
        print(f"{path.name}: {len(contents)} bytes")
